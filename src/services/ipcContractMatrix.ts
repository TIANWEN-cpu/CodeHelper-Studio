export type CapabilityStatus = 'available' | 'requires-environment' | 'degraded' | 'placeholder'

export interface IpcChannelContract {
  capability: string
  channel: string
  renderer: string
  service: string
  preload: 'invoke' | 'on'
  ipc: string
  request: string
  response: string
  status: CapabilityStatus
  note: string
}

type ContractDefinition = readonly [
  capability: string,
  channel: string,
  renderer: string,
  service: string,
  ipc: string,
  request: string,
  response: string,
  status: CapabilityStatus,
  note: string,
]

function invoke(...definition: ContractDefinition): IpcChannelContract {
  const [capability, channel, renderer, service, ipc, request, response, status, note] = definition
  return {
    capability,
    channel,
    renderer,
    service,
    preload: 'invoke',
    ipc,
    request,
    response,
    status,
    note,
  }
}

function event(...definition: ContractDefinition): IpcChannelContract {
  return { ...invoke(...definition), preload: 'on' }
}

